#!/usr/bin/env python3
"""Generate src/text/variantTable.ts — the CJK variant fold table.

Replaces the ~65 hand-grown pairs that used to live in entityMatch.ts
with the full maintained mapping, generated from the OpenCC
dictionaries (Apache-2.0, https://github.com/BYVoid/OpenCC):

  JPVariants.txt    Japanese shinjitai      -> standard traditional
  TWVariants.txt    Taiwan regional variants -> standard traditional
  HKVariants.txt    Hong Kong variants       -> standard traditional
  TSCharacters.txt  traditional              -> simplified (canonical)

Every variant character folds to ONE canonical (simplified) form.
The fold is for MATCHING KEYS ONLY — stored name forms are never
rewritten; the novel's original spellings stay the data.

The original hand pairs from entityMatch.ts are unioned in (their
canonical targets agree with the dictionaries; conflicts are
reported and the dictionary wins).

Usage (needs the opencc pip package for its dictionary files only):
  pip install opencc-python-reimplemented
  python3 tools/gen-variant-map.py
"""
import sys
from pathlib import Path

LEGACY_PAIRS = [
    ("黑", "黒"), ("泽", "沢"), ("泽", "澤"), ("岛", "島"), ("宫", "宮"),
    ("园", "園"), ("会", "會"), ("国", "國"), ("学", "學"), ("队", "隊"),
    ("长", "長"), ("门", "門"), ("风", "風"), ("云", "雲"), ("龙", "龍"),
    ("马", "馬"), ("车", "車"), ("书", "書"), ("语", "語"), ("时", "時"),
    ("现", "現"), ("点", "點"), ("线", "線"), ("气", "氣"), ("热", "熱"),
    ("电", "電"), ("话", "話"), ("说", "說"), ("读", "讀"), ("写", "寫"),
    ("听", "聽"), ("见", "見"), ("开", "開"), ("关", "關"), ("乐", "樂"),
    ("东", "東"), ("个", "個"), ("们", "們"), ("这", "這"), ("对", "對"),
    ("实", "實"), ("图", "圖"), ("广", "廣"), ("场", "場"), ("达", "達"),
    ("进", "進"), ("过", "過"), ("还", "還"), ("边", "邊"), ("远", "遠"),
    ("运", "運"), ("动", "動"), ("医", "醫"), ("员", "員"), ("圆", "圓"),
    ("团", "團"), ("响", "響"), ("与", "與"), ("为", "為"), ("后", "後"),
]

def load_dict(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in path.read_text(encoding="utf8").splitlines():
        if not line.strip():
            continue
        src, _, targets = line.partition("\t")
        first = targets.split(" ")[0] if targets else ""
        # char-level only: both sides exactly one character
        if len(src) == 1 and len(first) == 1:
            out[src] = first
    return out

def main() -> int:
    try:
        import opencc
    except ImportError:
        print("opencc package not found — pip install opencc-python-reimplemented", file=sys.stderr)
        return 1
    ddir = Path(opencc.__file__).parent / "dictionary"
    ts = load_dict(ddir / "TSCharacters.txt")
    variants: dict[str, str] = {}
    # JPVariants.txt runs traditional -> shinjitai in this dictionary
    # edition, so invert it: shinjitai form -> traditional standard.
    for line in (ddir / "JPVariants.txt").read_text(encoding="utf8").splitlines():
        if not line.strip():
            continue
        trad, _, jp_forms = line.partition("\t")
        if len(trad) != 1:
            continue
        for jp in jp_forms.split(" "):
            if len(jp) == 1:
                variants.setdefault(jp, trad)
    for fname in ("TWVariants.txt", "HKVariants.txt"):
        variants.update(load_dict(ddir / fname))

    def canon(ch: str) -> str:
        seen = set()
        cur = ch
        for _ in range(6):
            if cur in seen:
                break
            seen.add(cur)
            nxt = variants.get(cur, cur)
            nxt = ts.get(nxt, nxt)
            if nxt == cur:
                break
            cur = nxt
        return cur

    table: dict[str, str] = {}
    for src in set(ts) | set(variants):
        c = canon(src)
        if c != src and len(c) == 1:
            table[src] = c
    conflicts = []
    for a, b in LEGACY_PAIRS:
        for src, target in ((b, a),):
            if src in table and table[src] != target:
                conflicts.append((src, table[src], target))
            table.setdefault(src, target)
    for src, dict_target, legacy_target in sorted(conflicts):
        print(f"conflict: {src} dictionary->{dict_target} legacy->{legacy_target} (dictionary kept)")

    root = Path(__file__).resolve().parent.parent
    out_path = root / "src" / "text" / "variantTable.ts"
    lines = [
        "/**",
        " * GENERATED by tools/gen-variant-map.py from the OpenCC dictionaries",
        " * (Apache-2.0): JPVariants + TWVariants + HKVariants folded through",
        " * TSCharacters to one canonical simplified form per variant, unioned",
        " * with the original hand pairs. DO NOT EDIT BY HAND — regenerate.",
        f" * {len(table)} variant characters.",
        " */",
        "export const VARIANT_FOLD: Record<string, string> = {",
    ]
    items = sorted(table.items())
    for i in range(0, len(items), 8):
        chunk = items[i:i + 8]
        lines.append("  " + " ".join(f'"{k}":"{v}",' for k, v in chunk))
    lines.append("};")
    lines.append("")
    out_path.write_text("\n".join(lines), encoding="utf8")
    print(f"wrote {out_path} with {len(table)} entries")
    for probe in ("黒", "櫻", "邊", "齊", "廣", "國", "檸", "亞", "陸", "廳", "瀨", "爾"):
        print(f"  {probe} -> {table.get(probe, probe)}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
